// Looks every artist up on Deezer once and bakes id, photo and biggest song into artists.js.
// Run: node tools/fetch-artists.mjs   (prints each match so wrong picks are easy to spot)
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const POOLS = {
  rap: ['Drake', 'Kendrick Lamar', 'Travis Scott', 'Kanye West', 'J. Cole', 'Future', '21 Savage',
    'Lil Baby', 'Playboi Carti', 'Tyler, The Creator', 'A$AP Rocky', 'Metro Boomin', 'Lil Uzi Vert',
    'Eminem', 'Young Thug', 'Gunna', 'Don Toliver', 'Nicki Minaj', 'Juice WRLD', 'XXXTENTACION',
    'Pop Smoke', 'Lil Wayne', 'JAY-Z', 'Kid Cudi', 'Mac Miller', 'Central Cee', '2Pac', '50 Cent'],
  house: ['Fisher', 'GORDO', 'Chris Lake', 'John Summit', 'Dom Dolla', 'Mau P', 'Peggy Gou',
    'Fred again..', 'Calvin Harris', 'David Guetta', 'Swedish House Mafia', 'Disclosure', 'Kaytranada',
    'Mochakk', 'Chris Stussy', 'Keinemusik', 'Black Coffee', 'Adam Port', 'Anyma', 'Solomun',
    'MEDUZA', 'James Hype', 'Tiësto', 'HUGEL'],
  arab: ['Wegz', 'Marwan Pablo', 'Abyusif', 'Marwan Moussa', 'Afroto', 'Lege-Cy', 'Ali Loka',
    'Shahyn', 'Ziad Zaza', 'Mousv', 'Abo El Anwar', 'El Joker', 'Saint Levant', 'ElGrande Toto'],
};

// Exact Deezer ids for names that search can't settle on its own.
const PINNED = {};

const norm = s => s.toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '').replace(/[^a-z0-9]/g, '');
const sleep = ms => new Promise(r => setTimeout(r, ms));
async function get(url) {
  for (let i = 0; i < 4; i++) {
    const res = await fetch(url);
    const j = await res.json();
    if (!j.error) return j;
    await sleep(1500);
  }
  throw new Error('deezer failed: ' + url);
}

const out = [];
for (const [pool, names] of Object.entries(POOLS)) {
  for (const name of names) {
    let a;
    if (PINNED[name]) a = await get(`https://api.deezer.com/artist/${PINNED[name]}`);
    else {
      const { data } = await get(`https://api.deezer.com/search/artist?q=${encodeURIComponent(name)}&limit=15`);
      const exact = data.filter(d => norm(d.name) === norm(name));
      a = (exact.length ? exact : data).sort((x, y) => y.nb_fan - x.nb_fan)[0];
    }
    const top = await get(`https://api.deezer.com/artist/${a.id}/top?limit=1`);
    const song = top.data[0]?.title ?? '', t = top.data[0]?.id ?? 0;
    out.push({ pool, name, dz: a.id, t, img: a.picture_xl.replace('1000x1000', '500x500'), song });
    console.log(`${pool.padEnd(5)} ${name.padEnd(20)} -> ${a.name.padEnd(20)} ${String(a.nb_fan).padStart(9)} fans  "${song}"`);
    await sleep(250);
  }
}

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
writeFileSync(join(root, 'artists.js'), '// Generated by tools/fetch-artists.mjs\nconst ARTISTS = ' + JSON.stringify(out, null, 0).replace(/\},\{/g, '},\n{') + ';\n');
